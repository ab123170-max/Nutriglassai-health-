-- NutriGlass AI cloud sync schema
-- Run this script in Supabase Dashboard -> SQL Editor.
-- Every row is private to its authenticated owner. Never disable RLS.

create table if not exists public.health_records (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  record_id text not null,
  record_type text not null,
  payload jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now(),
  deleted_at timestamptz,
  unique (user_id, record_id)
);

create index if not exists health_records_owner_type_updated_idx
  on public.health_records (user_id, record_type, updated_at desc);

alter table public.health_records enable row level security;

drop policy if exists "Users read their own health records" on public.health_records;
create policy "Users read their own health records"
  on public.health_records for select to authenticated
  using (auth.uid() = user_id);

drop policy if exists "Users insert their own health records" on public.health_records;
create policy "Users insert their own health records"
  on public.health_records for insert to authenticated
  with check (auth.uid() = user_id);

drop policy if exists "Users update their own health records" on public.health_records;
create policy "Users update their own health records"
  on public.health_records for update to authenticated
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

drop policy if exists "Users delete their own health records" on public.health_records;
create policy "Users delete their own health records"
  on public.health_records for delete to authenticated
  using (auth.uid() = user_id);

-- Private bucket for progress photos and food scan images.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('health-photos', 'health-photos', false, 10485760, array['image/jpeg','image/png','image/webp'])
on conflict (id) do update set public = false;

drop policy if exists "Users read own health photos" on storage.objects;
create policy "Users read own health photos"
  on storage.objects for select to authenticated
  using (bucket_id = 'health-photos' and (storage.foldername(name))[1] = auth.uid()::text);

drop policy if exists "Users upload own health photos" on storage.objects;
create policy "Users upload own health photos"
  on storage.objects for insert to authenticated
  with check (bucket_id = 'health-photos' and (storage.foldername(name))[1] = auth.uid()::text);

drop policy if exists "Users update own health photos" on storage.objects;
create policy "Users update own health photos"
  on storage.objects for update to authenticated
  using (bucket_id = 'health-photos' and (storage.foldername(name))[1] = auth.uid()::text)
  with check (bucket_id = 'health-photos' and (storage.foldername(name))[1] = auth.uid()::text);

drop policy if exists "Users delete own health photos" on storage.objects;
create policy "Users delete own health photos"
  on storage.objects for delete to authenticated
  using (bucket_id = 'health-photos' and (storage.foldername(name))[1] = auth.uid()::text);
